const GLYPH_W = 5;
const ADVANCE = GLYPH_W + 1;

// Merge each horizontal run of the same non-transparent char into one rect.
function runs(rows, colorOf, px, x0, y0) {
  const out = [];
  rows.forEach((row, ry) => {
    let cx = 0;
    while (cx < row.length) {
      const ch = row[cx];
      if (ch === '.') { cx++; continue; }
      let end = cx;
      while (end + 1 < row.length && row[end + 1] === ch) end++;
      out.push(
        `<rect x="${x0 + cx * px}" y="${y0 + ry * px}" width="${(end - cx + 1) * px}" height="${px}" fill="${colorOf(ch)}"/>`,
      );
      cx = end + 1;
    }
  });
  return out;
}

export function sprite(rows, colors, px, x, y) {
  const colorOf = (ch) => {
    if (!(ch in colors)) throw new Error(`sprite: no color for "${ch}"`);
    return colors[ch];
  };
  return `<g shape-rendering="crispEdges">${runs(rows, colorOf, px, x, y).join('')}</g>`;
}

export function pixelText(str, px, x, y, color) {
  const chars = [...str.toUpperCase()];
  const parts = [];
  chars.forEach((c, i) => {
    const glyph = FONT[c];
    if (!glyph) throw new Error(`pixelText: unsupported character "${c}"`);
    parts.push(...runs(glyph, () => color, px, x + i * ADVANCE * px, y));
  });
  return `<g shape-rendering="crispEdges">${parts.join('')}</g>`;
}

export function textWidth(str, px) {
  const n = [...str].length;
  return n === 0 ? 0 : n * ADVANCE * px - px;
}
